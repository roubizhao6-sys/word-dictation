def replace_once(text: str, old: str, new: str, label: str) -> str:
    found = text.count(old)
    if found != 1:
        raise SystemExit(f"{label}: expected 1 match, found {found}")
    return text.replace(old, new, 1)


def clear_words(text: str) -> str:
    lines = text.splitlines(keepends=True)
    hits = [i for i, line in enumerate(lines) if line.startswith("const WORDS = ")]
    if len(hits) != 1:
        raise SystemExit(f"const WORDS lines: expected 1, found {len(hits)}")
    raw = lines[hits[0]].rstrip("\r\n")
    if not raw.endswith(";"):
        raise SystemExit("WORDS assignment is not a single statement")
    payload = raw[len("const WORDS = ") : -1]
    words = json.loads(payload)
    if not isinstance(words, list) or len(words) < 1:
        raise SystemExit("refusing to build a blank page from an already empty root word list")
    newline = "\n" if lines[hits[0]].endswith("\n") else ""
    lines[hits[0]] = "const WORDS = [];" + newline
    return "".join(lines)


def build_html(source: str) -> str:
    text = clear_words(source)
    for i, (old, new) in enumerate(REPLACEMENTS):
        text = replace_once(text, old, new, f"replacement {i}")
    if re.search(r"const WORDS = \[(?!])", text):
        raise SystemExit("blank page still contains a WORDS array literal")
    if text.count("const WORDS = [];") != 1:
        raise SystemExit("blank page is missing const WORDS = [];")
    if "dictation_idict_v1" in text or "word_dictation_db" in text:
        raise SystemExit("blank page still uses the full site storage keys")
    if 'src="config.js"' in text:
        raise SystemExit("blank page must load ../config.js so the OCR URL stays shared")
    if "暂无单词，请添加" not in text:
        raise SystemExit("blank page is missing the empty-state copy")
    return text


def main() -> None:
    check = "--check" in sys.argv
    source = SOURCE.read_text(encoding="utf-8")
    html = build_html(source)
    csv_text = CSV_HEADER
    json_text = "[]\n"
    if check:
        errors = []
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != html:
            errors.append("empty/index.html is out of date; run python3 scripts/build-empty-site.py")
        if not EMPTY_JSON.is_file() or EMPTY_JSON.read_text(encoding="utf-8") != json_text:
            errors.append("empty/words.json is out of date")
        if not EMPTY_CSV.is_file() or EMPTY_CSV.read_text(encoding="utf-8") != csv_text:
            errors.append("empty/words.csv is out of date")
        if errors:
            raise SystemExit("\n".join(errors))
        print("empty site matches index.html")
        return
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(html, encoding="utf-8")
    EMPTY_JSON.write_text(json_text, encoding="utf-8")
    EMPTY_CSV.write_text(csv_text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(html)} bytes)")


if __name__ == "__main__":
    main()
